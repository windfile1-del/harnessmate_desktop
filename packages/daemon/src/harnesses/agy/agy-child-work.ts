import {
  readChildOwnedTranscriptOnly,
  readVersionedChildRecord,
  scanVersionedChildRecords,
  type ChildRecordScanOptions,
  type ChildRecordSchemaVersion,
} from './native/child/record-parser.js';

export interface AgySubagentRecord {
  id: string;
  role?: string;
  typeName?: string;
  status: string;
  summary?: string;
  updatedAt?: number;
  schemaVersion?: ChildRecordSchemaVersion;
  spawnStepIndex?: number;
}

export interface AgySubagentDetail extends AgySubagentRecord {
  transcriptLines: string[];
  rawText?: string;
  truncated: boolean;
  transcriptSource?: 'child_jsonl' | 'unavailable';
  sourceUnavailableReason?: string;
}

/**
 * Strictly read-only, schema-gated, bounded enumeration of subagent metadata generated by AGY under
 * `<appDataPath>/brain/<nativeSessionId>/.system_generated/subagents/`.
 *
 * NP-05 guarantees:
 * - Supports versioned `app_v1` (E06 real App record shape) and `cli_legacy_v0` records.
 * - Fails closed on unknown/future record schemas, symlinks/Windows reparse points, and traversal.
 * - Enforces bounded directory scan and bounded file size caps.
 * - Never exposes raw host paths or `workspaceUris`.
 */
export function listAgySubagentRecords(
  appDataPath: string,
  nativeSessionId: string,
  opts?: ChildRecordScanOptions,
): AgySubagentRecord[] {
  const scan = scanVersionedChildRecords(appDataPath, nativeSessionId, opts);
  return scan.records.map((rec) => ({
    id: rec.recordId,
    ...(rec.role ? { role: rec.role } : {}),
    ...(rec.typeName ? { typeName: rec.typeName } : {}),
    status: rec.rawState,
    ...(rec.summary ? { summary: rec.summary } : {}),
    ...(rec.updatedAt !== undefined ? { updatedAt: rec.updatedAt } : {}),
    schemaVersion: rec.schemaVersion,
    ...(rec.spawnStepIndex !== undefined ? { spawnStepIndex: rec.spawnStepIndex } : {}),
  }));
}

/**
 * Strictly read-only child subagent detail reader.
 *
 * CRITICAL NP-05 FIX (S09 / R-04):
 * Reads ONLY the child's own sibling `<subagentId>.jsonl` when present.
 * NEVER falls back to parent `logs/transcript.jsonl` as a child transcript.
 */
export function readAgySubagentDetail(
  appDataPath: string,
  nativeSessionId: string,
  subagentId: string,
  opts?: ChildRecordScanOptions,
): AgySubagentDetail | null {
  const { record } = readVersionedChildRecord(appDataPath, nativeSessionId, subagentId, opts);
  if (!record) return null;

  const transcript = readChildOwnedTranscriptOnly(appDataPath, nativeSessionId, subagentId, {
    maxFileBytes: opts?.maxFileBytes,
    maxLines: opts?.maxTranscriptLines,
  });

  return {
    id: record.recordId,
    ...(record.role ? { role: record.role } : {}),
    ...(record.typeName ? { typeName: record.typeName } : {}),
    status: record.rawState,
    ...(record.summary ? { summary: record.summary } : {}),
    ...(record.updatedAt !== undefined ? { updatedAt: record.updatedAt } : {}),
    schemaVersion: record.schemaVersion,
    ...(record.spawnStepIndex !== undefined ? { spawnStepIndex: record.spawnStepIndex } : {}),
    transcriptLines: [...transcript.lines],
    ...(transcript.available ? { rawText: transcript.lines.join('\n') } : {}),
    truncated: Boolean(record.truncated || transcript.truncated),
    transcriptSource: transcript.available ? 'child_jsonl' : 'unavailable',
    ...(transcript.reasonCode ? { sourceUnavailableReason: transcript.reasonCode } : {}),
  };
}
