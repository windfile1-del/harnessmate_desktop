import fs from 'node:fs';
import path from 'node:path';
import { resolveManagedProfilePathSync } from './agy-profile-manager.js';

const MAX_READ_BYTES = 262_144;

export interface AgySubagentRecord {
  id: string;
  role?: string;
  typeName?: string;
  status: string;
  summary?: string;
  updatedAt?: number;
}

export interface AgySubagentDetail extends AgySubagentRecord {
  transcriptLines: string[];
  rawText?: string;
  truncated: boolean;
}

function readBoundedRegularFile(
  rootDir: string,
  segments: readonly string[],
): { text: string; truncated: boolean } | undefined {
  const safe = resolveManagedProfilePathSync(rootDir, segments, 'file');
  if (!safe) return undefined;
  const bytes = Math.min(safe.info.size, MAX_READ_BYTES);
  const fd = fs.openSync(safe.path, 'r');
  try {
    const buf = Buffer.alloc(bytes);
    const readBytes = fs.readSync(fd, buf, 0, bytes, 0);
    return {
      text: buf.subarray(0, readBytes).toString('utf8'),
      truncated: safe.info.size > MAX_READ_BYTES,
    };
  } finally {
    fs.closeSync(fd);
  }
}

/**
 * Strictly read-only enumeration of subagent metadata generated by AGY under
 * `<appDataPath>/brain/<nativeSessionId>/.system_generated/`.
 */
export function listAgySubagentRecords(
  appDataPath: string,
  nativeSessionId: string,
): AgySubagentRecord[] {
  if (!nativeSessionId.trim()) return [];
  const subagentsDir = resolveManagedProfilePathSync(
    appDataPath,
    ['brain', nativeSessionId.trim(), '.system_generated', 'subagents'],
    'directory',
  );
  if (!subagentsDir) return [];

  const records: AgySubagentRecord[] = [];
  for (const entry of fs.readdirSync(subagentsDir.path)) {
    if (!entry.endsWith('.json')) continue;
    const read = readBoundedRegularFile(
      appDataPath,
      ['brain', nativeSessionId.trim(), '.system_generated', 'subagents', entry],
    );
    if (!read) continue;
    try {
      const parsed = JSON.parse(read.text) as Record<string, unknown>;
      const id =
        (typeof parsed.id === 'string' && parsed.id.trim()) || path.basename(entry, '.json');
      records.push({
        id,
        role: typeof parsed.role === 'string' ? parsed.role : undefined,
        typeName: typeof parsed.typeName === 'string' ? parsed.typeName : undefined,
        status: typeof parsed.status === 'string' ? parsed.status : 'unknown',
        summary: typeof parsed.summary === 'string' ? parsed.summary : undefined,
        updatedAt: typeof parsed.updatedAt === 'number' ? parsed.updatedAt : undefined,
      });
    } catch {
      // Ignore corrupt/partial subagent file
    }
  }
  return records;
}

export function readAgySubagentDetail(
  appDataPath: string,
  nativeSessionId: string,
  subagentId: string,
): AgySubagentDetail | null {
  if (!nativeSessionId.trim() || !subagentId.trim()) return null;
  const cleanSess = nativeSessionId.trim();
  const cleanSub = subagentId.trim();

  const metaRead = readBoundedRegularFile(appDataPath, [
    'brain',
    cleanSess,
    '.system_generated',
    'subagents',
    `${cleanSub}.json`,
  ]);
  if (!metaRead) return null;

  let meta: Record<string, unknown>;
  try {
    meta = JSON.parse(metaRead.text) as Record<string, unknown>;
  } catch {
    return null;
  }

  const transcriptRead =
    readBoundedRegularFile(appDataPath, [
      'brain',
      cleanSess,
      '.system_generated',
      'subagents',
      `${cleanSub}.jsonl`,
    ]) ??
    readBoundedRegularFile(appDataPath, [
      'brain',
      cleanSess,
      '.system_generated',
      'logs',
      'transcript.jsonl',
    ]);

  const transcriptLines = transcriptRead
    ? transcriptRead.text
        .split(/\r?\n/)
        .map((l) => l.trim())
        .filter(Boolean)
        .slice(-200)
    : [];

  return {
    id: cleanSub,
    role: typeof meta.role === 'string' ? meta.role : undefined,
    typeName: typeof meta.typeName === 'string' ? meta.typeName : undefined,
    status: typeof meta.status === 'string' ? meta.status : 'unknown',
    summary: typeof meta.summary === 'string' ? meta.summary : undefined,
    updatedAt: typeof meta.updatedAt === 'number' ? meta.updatedAt : undefined,
    transcriptLines,
    rawText: transcriptRead?.text,
    truncated: Boolean(metaRead.truncated || transcriptRead?.truncated),
  };
}
